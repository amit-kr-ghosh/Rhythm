/**
 * Prints SQL that seeds the default subjects, plans and weekly timetable for ONE user.
 *
 *   tsx scripts/gen-seed-sql.ts <user-uuid> > supabase/seed.generated.sql
 *
 * Without an argument a clearly-marked placeholder is emitted and the script refuses to run in psql until you
 * replace it. Rows use the same deterministic ids as the app, and ON CONFLICT DO NOTHING, so the seed is idempotent
 * and the app's own first-run seeding (which pushes identical ids) will not create duplicates.
 * Run it in the Supabase SQL editor (as postgres) or with psql; it needs no service-role key in the app.
 */
import { buildDefaultPlans, buildDefaultSubjects, buildDefaultTemplates } from '../src/domain/defaults';
import { toCloudRow, CLOUD_TABLE } from '../src/domain/sync';
import type { EntityKind } from '../src/domain/types';

const PLACEHOLDER = '00000000-0000-0000-0000-000000000000';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const arg = process.argv[2];
if (arg !== undefined && !UUID.test(arg)) {
  console.error(`Invalid user id "${arg}": expected a UUID (auth.users.id).`);
  process.exit(1);
}
const userId = arg ?? PLACEHOLDER;

const JSON_COLS = new Set(['snapshot', 'milestones', 'recurrence', 'done_dates', 'timer', 'weights', 'motivation', 'whys', 'target_history']);
const INT_ARRAY_COLS = new Set(['weekdays']);

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
function lit(col: string, v: unknown): string {
  if (v === null || v === undefined) return 'null';
  if (INT_ARRAY_COLS.has(col)) return `array[${(v as number[]).join(',')}]::integer[]`;
  if (JSON_COLS.has(col)) return `${q(JSON.stringify(v))}::jsonb`;
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return q(String(v));
}

function insert(kind: EntityKind, rows: object[]): string {
  if (rows.length === 0) return '';
  const mapped = rows.map((r) => toCloudRow(kind, r as Record<string, unknown>, userId));
  const cols = Object.keys(mapped[0]!);
  const values = mapped.map((r) => `  (${cols.map((c) => lit(c, r[c])).join(', ')})`).join(',\n');
  return `insert into public.${CLOUD_TABLE[kind]} (${cols.join(', ')}) values\n${values}\non conflict (user_id, id) do nothing;\n`;
}

const now = new Date().toISOString();
const from = now.slice(0, 10);
const out: string[] = [
  `-- Rhythm default seed for user ${userId}`,
  '-- Generated by scripts/gen-seed-sql.ts — do not edit by hand; re-run the generator instead.',
  `-- Timetable versions take effect from ${from}.`,
  'begin;',
];
if (userId === PLACEHOLDER) {
  out.push(
    '-- !!! PLACEHOLDER USER ID: re-run with  tsx scripts/gen-seed-sql.ts <your-auth-user-uuid>  !!!',
    "do $$ begin raise exception 'seed.sql was generated with the placeholder user id; regenerate it with a real auth.users id'; end $$;",
  );
}
out.push(
  insert('subjects', buildDefaultSubjects(now)),
  insert('plans', buildDefaultPlans(now)),
  insert('templates', buildDefaultTemplates(from, now)),
  'commit;',
);
process.stdout.write(out.join('\n') + '\n');
